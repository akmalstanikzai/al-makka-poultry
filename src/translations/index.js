export const getLocalizedTransactionType = (type, lang) => {
    const t = translations[lang];
    if (type === 'sale')
        return t.feedSaleTx;
    if (type === 'payment')
        return t.cashPaymentTx;
    if (type === 'purchase')
        return t.supplierPurchaseTx;
    return type;
};
export const getLocalizedTransactionDescription = (desc, lang) => {
    const t = translations[lang];
    if (!desc)
        return '';
    if (desc.includes('خرید دانه') || desc.includes('د دانې پېرود') || desc.includes('Feed Purchase') || desc.includes('فروش دانه') || desc.includes('د دانې پلور')) {
        return desc
            .replace(/فروش دانه/g, t.feedSaleTx)
            .replace(/خرید دانه/g, t.feedSaleTx)
            .replace(/د دانې پلور/g, t.feedSaleTx)
            .replace(/د دانې پېرود/g, t.feedSaleTx);
    }
    if (desc.includes('رسید نقدی') || desc.includes('دریافت وجه') || desc.includes('د نغدو ترلاسه کول') || desc.includes('Cash Received') || desc.includes('نغدي ترلاسه شوي')) {
        return t.cashPaymentTx;
    }
    if (desc.includes('خرید مواد خام') || desc.includes('د خامو موادو رانیول') || desc.includes('Raw Material Purchase')) {
        return t.supplierPurchaseTx;
    }
    if (desc.includes('پرداخت وجه') || desc.includes('تادیه') || desc.includes('Disbursement') || desc.includes('Supplier Payment') || desc.includes('پرداخت نقدی به تامین‌کننده')) {
        return t.supplierPaymentTx;
    }
    return desc;
};
