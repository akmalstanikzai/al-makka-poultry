export const getLocalizedItemName = (name, lang) => {
    if (itemLocalizations[name] && itemLocalizations[name][lang]) {
        return itemLocalizations[name][lang];
    }
    // Try case-insensitive or partial match
    for (const [key, mapping] of Object.entries(itemLocalizations)) {
        if (name.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(name.toLowerCase())) {
            if (mapping[lang])
                return mapping[lang];
        }
    }
    return name;
};
